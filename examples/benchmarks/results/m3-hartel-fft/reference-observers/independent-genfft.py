from pathlib import Path
import math,cmath,re,json
p=Path(__file__).resolve().parent

def generate(power):
 half=1<<power;n=2*half;b=lambda stage,index:f'b_{stage}_{index}';r=lambda stage,index:f'r_{stage}_{index}'
 declarations=[]
 for i in range(n):
  reverse=int(format(i,'0'+str(power+1)+'b')[::-1],2)
  declarations.append(f'LET {b(0,reverse)}=head i{i+1} IN\n ')
  if i<n-1:declarations.append(f'LET i{i+2}=tail i{i+1} IN\n ')
 equations=[]
 for m in range(power+1):
  for k in range(half):
   mask=(1<<m)-1;i=((k>>m)<<(m+1))+(k&mask);j=i+(1<<m);h=(k*(1<<(power-m)))%half
   equations.append(f'{b(m+1,i)}=add_x {b(m,i)} {r(m,k)}; {b(m+1,j)}=sub_x {b(m,i)} {r(m,k)}; {r(m,k)}=mul_x {b(m,j)} w_{h}')
 roots=[f'w_{i}=fw_d sector_{n} {i}.0'for i in range(half)]
 output=':\n '.join(':'.join(b(power+1,i)for i in range(first,min(first+8,n)))for first in range(0,n,8))
 join=';\n '
 return f"sed -e 's/^/||SYNTH_{n} /' <<'end'     \nsynth_fft_{n} i1\n="+''.join(declarations)+'LET\n '+join.join(equations)+';\n '+join.join(roots)+'\n IN '+output+f':NIL;\nINLINE sector_{n}=pi/{half}.0;\n\nend\n'

for profile,maximum,checksum in [('smoke',3,'417707/5532'),('normal',6,'5925859/79360'),('large',8,'31387091/426210')]:
 generated=''.join(generate(i)for i in range(1,maximum+1)).encode();raw=(p/'genfft'/(profile+'.program')).read_bytes();assert generated==raw,profile
 assert str(sum(raw)+len(raw))+'/'+str(len(raw))==checksum
meta=[]
raw=(p/'genfft/large.program').read_text();blocks=[b for b in re.split(r'(?m)(?=^sed -e )',raw)if b]
assert len(blocks)==8
for block in blocks:
 n=int(re.search(r'SYNTH_(\d+)',block)[1]);power=n.bit_length()-2;inputs=[complex((i*17)%29-14,(i*13)%19-9)for i in range(n)];memo={};equations={}
 for name,index in re.findall(r'LET (b_0_\d+)=head i(\d+) IN',block):memo[name]=inputs[int(index)-1]
 for name,sector,index in re.findall(r'(w_\d+)=fw_d sector_(\d+) (\d+)\.0',block):
  assert int(sector)==n;memo[name]=cmath.exp(2j*math.pi*int(index)/n)
 for name,operation,left,right in re.findall(r'([br]_\d+_\d+)=(add_x|sub_x|mul_x) ([br]_\d+_\d+) ([rw]_\d+(?:_\d+)?)',block):
  assert name not in equations;equations[name]=(operation,left,right)
