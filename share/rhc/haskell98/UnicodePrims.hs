-- Module UnicodePrims: rhc's Unicode, the module the Report's code imports
-- ("Source of primitive Unicode functions") and defines nowhere. It is
-- rhc's, not the Report's (overlay ov.char.prims), and a program cannot
-- import it.
--
-- The general category and the simple case mappings of every code point,
-- from Rune's lib/unicode at its version of Unicode, 18.0.0 (D21): its
-- tables, lib/unicode/code_point_data.sml, which bin/rune-generate unicode
-- writes, are copied here as they are written, and a test holds each
-- string here to that file's (hs/library/unicode). No SML is below these
-- functions (D26, A): they read the tables in Haskell, as code_point.sml
-- reads them in SML.

module UnicodePrims (
    primUnicodeMaxChar, primUnicodeIsPrint, primUnicodeIsUpper,
    primUnicodeIsLower, primUnicodeIsAlphaNum, primUnicodeToUpper,
    primUnicodeToLower
  ) where

import PreludeBuiltin (Arr, arr_new, arr_set, arr_get, arr_size, unsafe_perform_io,
                       char_ord, char_chr)

-- the greatest character, U+10FFFF: Char holds every code point,
-- surrogates among them (D21)
primUnicodeMaxChar :: Char
primUnicodeMaxChar =  '\x10FFFF'

-- The predicates of chapter 19, by the general category:
--   * lower case: Ll;
--   * upper case: every other letter, Lu, Lt, Lm and Lo, as 19 says ("any
--     alphabetic character which is not lower case is treated as upper
--     case"; R38, where D38 follows the text);
--   * alphanumeric: the letters, and the numbers Nd, Nl, No;
--   * printable: all but the controls, formats, surrogates, private uses,
--     the unassigned, and the separators of lines and paragraphs.
primUnicodeIsLower, primUnicodeIsUpper, primUnicodeIsAlphaNum, primUnicodeIsPrint
                   :: Char -> Bool
primUnicodeIsLower c    = category c == 1
primUnicodeIsUpper c    = let g = category c in g <= 4 && g /= 1
primUnicodeIsAlphaNum c = let g = category c in g <= 4 || (g >= 8 && g <= 10)
primUnicodeIsPrint c    = category c <= 22

-- the simple case mappings: ASCII by its rule, the rest by the runs
primUnicodeToUpper, primUnicodeToLower :: Char -> Char
primUnicodeToUpper c
  | n < 128   = if n >= 97 && n <= 122 then char_chr (n - 32) else c
  | otherwise = char_chr (mapping upper n)
  where n = char_ord c
primUnicodeToLower c
  | n < 128   = if n >= 65 && n <= 90 then char_chr (n + 32) else c
  | otherwise = char_chr (mapping lower n)
  where n = char_ord c

-- the general category of a character, as a number: its position in
-- Lu Ll Lt Lm Lo, Mn Mc Me, Nd Nl No, Pc Pd Ps Pe Pi Pf Po, Sm Sc Sk So,
-- Zs Zl Zp, Cc Cf Cs Co Cn (29, the unassigned)
category           :: Char -> Int
category c
  | n < 256   = arr_get latin1_ n
  | otherwise = rangeValue category_ n
  where n = char_ord c

-- the value of the range (triples lo, hi, value) that holds n, or Cn's
rangeValue         :: Arr Int -> Int -> Int
rangeValue v n     =  go 0 (arr_size v `div` 3)
  where
    go lo hi
      | lo >= hi                   = 29
      | n < arr_get v (3 * m)      = go lo m
      | n > arr_get v (3 * m + 1)  = go (m + 1) hi
      | otherwise                  = arr_get v (3 * m + 2)
      where m = (lo + hi) `div` 2

-- the mapping of n by the run (quadruples lo, hi, step, d) that holds it,
-- n + d, or n itself
mapping            :: Arr Int -> Int -> Int
mapping v n        =  go 0 (arr_size v `div` 4)
  where
    go lo hi
      | lo >= hi                   = n
      | n < arr_get v (4 * m)      = go lo m
      | n > arr_get v (4 * m + 1)  = go (m + 1) hi
      | (n - arr_get v (4 * m)) `mod` arr_get v (4 * m + 2) == 0
                                   = n + arr_get v (4 * m + 3)
      | otherwise                  = n
      where m = (lo + hi) `div` 2

-- ---- the tables, read the first time one is used ----

-- the numbers of a string, each in base 32, most significant digit first:
-- a character from "]" to "|" is a digit (0 to 31) with more of its number
-- after it, and one from "0" to "O" the last digit (0 to 31)
numbers            :: String -> [Int]
numbers s          =  go 0 s
  where
    go v []       = []
    go v (c:cs)
      | k >= 93   = go (32 * v + k - 93) cs
      | otherwise = (32 * v + k - 48) : go 0 cs
      where k = char_ord c

-- ranges: the distance of the first code point from the end of the range
-- before, the length less one, the value; as lo, hi, value
ranges             :: [Int] -> [Int]
ranges xs          =  go 0 xs
  where
    go next (d : len : value : rest) = let lo = next + d
                                           hi = lo + len
                                       in lo : hi : value : go (hi + 1) rest
    go _ _ = []

-- runs: the distance of the first code point from the end of the run
-- before, the distance to its last, the step, and the distance of each
-- mapping, written 2 d, or -2 d - 1 where d is below 0; as lo, hi, step, d
runs               :: [Int] -> [Int]
runs xs            =  go 0 xs
  where
    go next (d : len : step : e : rest) = let lo = next + d
                                              hi = lo + len
                                          in lo : hi : step : distance e : go (hi + 1) rest
    go _ _ = []
    distance e = if e `mod` 2 == 0 then e `div` 2 else negate ((e + 1) `div` 2)

-- an array of the numbers
array_             :: [Int] -> Arr Int
array_ xs          =  unsafe_perform_io (do
                          a <- arr_new (length xs) 0
                          sequence_ [arr_set a i x | (i, x) <- zip [0..] xs]
                          return a)

latin1_, category_, upper, lower :: Arr Int
latin1_            =  array_ [char_ord c - 48 | c <- latin1]
category_          =  array_ (ranges (numbers categoryTable))
upper              =  array_ (runs (numbers upperTable))
lower              =  array_ (runs (numbers lowerTable))

